import '@testing-library/jest-dom'

// GSAP's ScrollTrigger calls window.matchMedia at registration time.
// jsdom doesn't implement it, so we provide a minimal stub.
Object.defineProperty(window, 'matchMedia', {
  writable: true,
  value: (query: string) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  }),
})
